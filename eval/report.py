"""Renders docs/EVALUATION.md from evaluation results."""
from collections import Counter
from typing import Dict, List

from .harness import LINE_TOLERANCE, Sample

ENGINE_LABEL = {
    "sast": "SAST only (Bandit)",
    "rules": "Rule engine (OT/ICS + config + secrets)",
    "llm": "LLM only",
    "hybrid": "Hybrid pipeline",
}
CATEGORY_LABEL = {"ot": "OT / ICS", "config": "Config", "appsec": "AppSec", "secrets": "Secrets"}


def _f(value) -> str:
    return "n/a" if value is None else f"{value:.2f}"


def _row(name: str, m: Dict) -> str:
    return (f"| {name} | {m['samples']} | {m['tp']} | {m['fp']} | {m['fn']} | {_f(m['precision'])} | "
            f"{_f(m['recall'])} | {_f(m['f1'])} | {_f(m['fp_rate_safe'])} |")


HEADER = ("| Engine | Samples | TP | FP | FN | Precision | Recall | F1 | FP rate (safe) |\n"
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|")


def _interpretation(results: Dict[str, Dict]) -> List[str]:
    notes = []
    rules, sast = results.get("rules"), results.get("sast")
    if rules and rules["status"] != "not_run":
        ot = rules["by_category"].get("ot", {})
        cfg = rules["by_category"].get("config", {})
        app = rules["by_category"].get("appsec", {})
        notes.append(f"The deterministic rule engine reaches recall {_f(ot.get('recall'))} on OT/ICS and "
                     f"{_f(cfg.get('recall'))} on configuration samples, with a false-positive rate of "
                     f"{_f(ot.get('fp_rate_safe'))} on safe OT samples. These samples were written together with the "
                     "rules, so the numbers show the rules behave as specified; they are not an estimate of "
                     "performance on unseen code.")
        notes.append(f"Its recall on classic AppSec samples is {_f(app.get('recall'))}: by design the rule packs do "
                     "not try to detect SQL injection, XSS or memory-safety bugs. That gap is what SAST and the LLM "
                     "are for.")
    if sast and sast["status"] != "not_run":
        app = sast["by_category"].get("appsec", {})
        notes.append(f"Bandit only analyses Python, so it misses every JavaScript, Java, C++ and Go sample; its AppSec "
                     f"recall is {_f(app.get('recall'))} and its overall precision {_f(sast['precision'])} "
                     "(import-level warnings such as B401 count as false positives here).")
    llm, hybrid = results.get("llm"), results.get("hybrid")
    if not llm or llm["status"] == "not_run":
        notes.append("**LLM and hybrid engines have not been measured yet.** No recorded model responses are "
                     "committed, and numbers are never made up. Run `python -m eval.run --engine all --live "
                     "--record --write` once with a configured `OPENAI_MODEL` to record responses; afterwards the "
                     "offline evaluation replays them for free.")
    else:
        notes.append(f"The LLM alone reaches precision {_f(llm['precision'])} and recall {_f(llm['recall'])}.")
        if hybrid and hybrid["status"] != "not_run" and rules:
            delta = (hybrid["recall"] or 0) - (rules["recall"] or 0)
            notes.append(f"Adding the LLM changes overall recall by {delta:+.2f} compared to the rule engine alone.")
            if (hybrid["fp_rate_safe"] or 0) > (rules["fp_rate_safe"] or 0):
                notes.append(f"Where the LLM hurts: it raises the false-positive rate on safe samples from "
                             f"{_f(rules['fp_rate_safe'])} to {_f(hybrid['fp_rate_safe'])}.")
    return notes


def render_markdown(results: Dict[str, Dict], samples: List[Sample], date: str) -> str:
    counts = Counter(s.category for s in samples)
    safe = sum(1 for s in samples if s.safe)
    lines = [
        "# Evaluation",
        "",
        f"_Generated by `python -m eval.run --write` on {date}._",
        "",
        "## Dataset",
        "",
        f"{len(samples)} labelled samples ({len(samples) - safe} vulnerable, {safe} safe): "
        + ", ".join(f"{CATEGORY_LABEL.get(c, c)} {n}" for c, n in sorted(counts.items())) + ".",
        "Ground truth lives in `eval/dataset.yaml`. A finding counts as a true positive when it is in the same file, "
        f"within {LINE_TOLERANCE} lines of the expected line, and has the expected rule id or CWE. Every other finding "
        "is a false positive. *FP rate (safe)* is the share of safe samples with at least one finding.",
        "",
        "## Results",
        "",
        HEADER,
    ]
    for engine, r in results.items():
        if r["status"] == "not_run":
            lines.append(f"| {ENGINE_LABEL.get(engine, engine)} | not run | | | | | | | |")
        else:
            lines.append(_row(ENGINE_LABEL.get(engine, engine), r))

    lines += ["", "### By category", ""]
    for engine, r in results.items():
        if r["status"] == "not_run":
            continue
        lines += [f"**{ENGINE_LABEL.get(engine, engine)}**", "", HEADER.replace("Engine", "Category")]
        lines += [_row(CATEGORY_LABEL.get(c, c), m) for c, m in r["by_category"].items()]
        lines.append("")

    lines += ["## Interpretation", ""] + [f"- {n}" for n in _interpretation(results)]
    lines += [
        "",
        "## Reproduce",
        "",
        "```powershell",
        "backend\\venv\\Scripts\\python -m eval.run --engine all          # offline, free",
        "backend\\venv\\Scripts\\python -m eval.run --engine rules --check  # CI gate",
        "```",
        "",
    ]
    return "\n".join(lines)
