import { countBySeverity, normalizeSeverity, SEVERITIES, sortBySeverity } from './severity';

const COLORS = {
  CRITICAL: '#f43f5e',
  HIGH: '#fb923c',
  MEDIUM: '#facc15',
  LOW: '#34d399',
  INFO: '#38bdf8',
};

export function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/**
 * Build a standalone HTML report. Every value coming from the AI is escaped because
 * the findings quote attacker-controlled source code.
 */
export function buildHtmlReport({ findings, target, meta, generatedAt = new Date() }) {
  const sorted = sortBySeverity(findings);
  const counts = countBySeverity(findings);

  const summary = SEVERITIES.map(
    (s) => `<div class="stat" style="--c:${COLORS[s]}"><b>${counts[s]}</b><span>${s}</span></div>`,
  ).join('');

  const cards = sorted
    .map((f) => {
      const sev = normalizeSeverity(f.severity);
      return `<article style="--c:${COLORS[sev]}">
  <header><span class="sev">${sev}</span><h2>${escapeHtml(f.vulnerability)}</h2><code>${escapeHtml(f.file)} : ${escapeHtml(f.line)}</code></header>
  <ul class="meta"><li>${escapeHtml(f.cwe)}</li><li>${escapeHtml(f.owasp)}</li><li>Confidence: ${escapeHtml(f.confidence)}</li><li>${escapeHtml(f.source)}</li></ul>
  <p>${escapeHtml(f.risk_explanation)}</p>
  <pre>${escapeHtml(f.secure_code_snippet)}</pre>
</article>`;
    })
    .join('\n');

  const metaLine = meta
    ? `${meta.files_scanned} file(s) scanned · ${meta.paranoia_level} mode · ${escapeHtml(meta.model)} · ${(meta.duration_ms / 1000).toFixed(1)}s`
    : '';

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Security Report - ${escapeHtml(target)}</title>
<style>
body{margin:0;background:#0b1120;color:#e2e8f0;font:15px/1.6 system-ui,-apple-system,Segoe UI,sans-serif;padding:40px 16px}
main{max-width:920px;margin:0 auto}h1{margin:0 0 4px;font-size:28px}.sub{color:#94a3b8;margin:0 0 28px}
.stats{display:grid;grid-template-columns:repeat(5,1fr);gap:10px;margin-bottom:32px}
.stat{background:#111a2e;border:1px solid #1e293b;border-top:3px solid var(--c);border-radius:10px;padding:14px;text-align:center}
.stat b{display:block;font-size:26px;color:var(--c)}.stat span{font-size:11px;letter-spacing:.08em;color:#94a3b8}
article{background:#111a2e;border:1px solid #1e293b;border-left:4px solid var(--c);border-radius:10px;padding:18px 20px;margin-bottom:16px}
article header{display:flex;flex-wrap:wrap;align-items:center;gap:10px}article h2{font-size:17px;margin:0;flex:1}
.sev{font-size:11px;font-weight:700;color:var(--c);border:1px solid var(--c);border-radius:999px;padding:2px 10px}
code,pre{font-family:ui-monospace,Consolas,monospace;font-size:13px}code{color:#94a3b8}
.meta{display:flex;flex-wrap:wrap;gap:8px;padding:0;list-style:none;margin:12px 0}.meta li{background:#0b1120;border:1px solid #1e293b;border-radius:6px;padding:2px 10px;font-size:12px;color:#cbd5e1}
pre{background:#0b1120;border:1px solid #1e293b;border-radius:8px;padding:14px;white-space:pre-wrap;color:#7dd3fc;overflow-x:auto}
footer{color:#64748b;font-size:12px;margin-top:32px;text-align:center}
@media(max-width:600px){.stats{grid-template-columns:repeat(3,1fr)}}
</style></head><body><main>
<h1>Security Audit Report</h1>
<p class="sub">Target: <b>${escapeHtml(target)}</b> · ${generatedAt.toLocaleString()}<br>${metaLine}</p>
<section class="stats">${summary}</section>
${cards || '<p>No vulnerabilities detected. Code passes the security baseline.</p>'}
<footer>Generated by AI AppSec Code Reviewer · SAST + AI hybrid pipeline</footer>
</main></body></html>`;
}

export function downloadFile(filename, content, type) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}
